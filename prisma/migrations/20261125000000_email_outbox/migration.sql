-- ─── Email outbox (replaces the BullMQ/Redis \"emails\" queue) ─────────────────
--
-- Booking emails are enqueued as rows here and delivered by the maintenance
-- loop (apps/api/src/maintenance.ts) with at-least-once semantics:
--
--   * rows are claimed with FOR UPDATE SKIP LOCKED, so multiple API instances
--     can drain concurrently without double-sending;
--   * attempts/next_attempt_at implement exponential backoff and a give-up cap;
--   * status SENDING older than 5 minutes is reclaimed (process crash during
--     send) by the drainer;
--   * SENT rows are pruned after EMAIL_OUTBOX_RETAIN_SENT_DAYS.
--
-- Zero Redis commands, no extra broker to run or monitor.

CREATE TABLE IF NOT EXISTS "email_outbox" (
  "id"              TEXT NOT NULL,
  "type"            TEXT NOT NULL,
  "payload"         JSONB NOT NULL,
  "status"          TEXT NOT NULL DEFAULT 'PENDING',
  "attempts"        INTEGER NOT NULL DEFAULT 0,
  "last_error"      TEXT,
  "next_attempt_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "created_at"      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- No DB default: generated by Prisma (@updatedAt); every raw UPDATE below
  -- sets it explicitly. Keeping it default-free matches the Prisma schema
  -- exactly, so `migrate dev` sees no drift.
  "updated_at"      TIMESTAMP(3) NOT NULL,
  "sent_at"         TIMESTAMP(3),
  CONSTRAINT "email_outbox_pkey" PRIMARY KEY ("id")
);

CREATE INDEX IF NOT EXISTS "email_outbox_status_next_attempt_at_idx"
  ON "email_outbox" ("status", "next_attempt_at");

CREATE INDEX IF NOT EXISTS "email_outbox_created_at_idx"
  ON "email_outbox" ("created_at");
